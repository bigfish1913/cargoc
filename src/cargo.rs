//! Cargo discovery shared by setup and execution. Never canonicalize the path
//! used to launch Cargo: Rustup dispatch depends on the `cargo` invocation name.
use crate::{
    Result, fail,
    util::{absolute, identity_path, same_or_descendant},
};
use std::{
    env,
    ffi::OsStr,
    fs,
    io::Read,
    path::{Path, PathBuf},
    process::Command,
};

const DEPTH: &str = "CARGOC_FORWARD_DEPTH";

/// Also bounds recursion through renamed/copied wrappers or third-party scripts.
pub fn command(path: &Path) -> Result<Command> {
    let depth = env::var(DEPTH)
        .unwrap_or_default()
        .parse::<u32>()
        .unwrap_or(0);
    if depth >= 8 {
        return fail("Cargo wrapper recursion detected; configure the real Cargo executable");
    }
    let mut command = Command::new(path);
    command.env(DEPTH, (depth + 1).to_string());
    Ok(command)
}

pub(crate) fn candidates(program: &Path, search: &OsStr) -> Vec<PathBuf> {
    let bases = if program.is_absolute() || program.components().count() > 1 {
        vec![program.to_path_buf()]
    } else {
        env::split_paths(search)
            .map(|dir| dir.join(program))
            .collect()
    };
    #[cfg(windows)]
    {
        let extensions = env::var("PATHEXT").unwrap_or_else(|_| ".COM;.EXE;.BAT;.CMD".into());
        bases
            .into_iter()
            .flat_map(|base| {
                if base.extension().is_some() {
                    return vec![base];
                }
                extensions
                    .split(';')
                    .filter(|ext| {
                        [".exe", ".com", ".bat", ".cmd"]
                            .iter()
                            .any(|known| ext.eq_ignore_ascii_case(known))
                    })
                    .map(|ext| base.with_extension(&ext[1..]))
                    .collect::<Vec<_>>()
            })
            .collect()
    }
    #[cfg(not(windows))]
    bases
}

pub(crate) fn generated_shim(path: &Path) -> Result<bool> {
    let mut header = Vec::new();
    fs::File::open(path)?.take(512).read_to_end(&mut header)?;
    Ok([
        b"# Generated by cargoc.".as_slice(),
        b"rem Generated by cargoc.".as_slice(),
    ]
    .iter()
    .any(|marker| header.windows(marker.len()).any(|part| part == *marker)))
}

pub fn validate_path(path: &Path) -> Result<()> {
    if !path.is_file() {
        return fail(format!(
            "Cargo executable does not exist: {}",
            path.display()
        ));
    }
    if identity_path(path)? == identity_path(&env::current_exe()?)?
        || same_or_descendant(path, &crate::integration::shim_dir())?
        || generated_shim(path)?
    {
        return fail("The configured Cargo executable points back to cargoc or its shim");
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if path.metadata()?.permissions().mode() & 0o111 == 0 {
            return fail(format!("Cargo is not executable: {}", path.display()));
        }
    }
    Ok(())
}

pub fn resolve(program: &Path, exclude: Option<&Path>) -> Result<PathBuf> {
    let explicit = program.is_absolute() || program.components().count() > 1;
    let search = env::var_os("PATH").unwrap_or_default();
    for path in candidates(program, &search) {
        if !path.is_file() {
            continue;
        }
        if let Some(dir) = exclude
            && same_or_descendant(&path, dir)?
        {
            continue;
        }
        if let Err(error) = validate_path(&path) {
            if explicit {
                return Err(error);
            }
            continue;
        }
        return absolute(&path);
    }
    fail(format!(
        "Cargo executable not found (excluding cargoc shims): {}",
        program.display()
    ))
}

pub fn version_number(text: &str) -> Option<(u32, u32)> {
    let mut words = text.split_whitespace();
    if words.next()? != "cargo" {
        return None;
    }
    let mut version = words.next()?.split('.');
    Some((version.next()?.parse().ok()?, version.next()?.parse().ok()?))
}

pub fn verify(path: &Path) -> Result<()> {
    validate_path(path)?;
    let output = command(path)?.arg("--version").output()?;
    if !output.status.success()
        || version_number(&String::from_utf8_lossy(&output.stdout)).is_none()
    {
        return fail(format!(
            "Not a working Cargo executable: {}",
            path.display()
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn candidates_preserve_directory_order() {
        let paths = [PathBuf::from("first"), PathBuf::from("second")];
        let search = env::join_paths(paths).unwrap();
        let found = candidates(Path::new("cargo"), &search);
        assert!(!found.is_empty());
        let boundary = found
            .iter()
            .position(|path| path.starts_with("second"))
            .unwrap();
        assert!(
            found[..boundary]
                .iter()
                .all(|path| path.starts_with("first"))
        );
        assert!(
            found[boundary..]
                .iter()
                .all(|path| path.starts_with("second"))
        );
        #[cfg(windows)]
        assert!(found.iter().all(|path| path.extension().is_some()));
    }
    #[test]
    fn version_requires_cargo_identity() {
        assert_eq!(
            version_number("cargo 1.99.1 (test)\nrelease: 1.99.1"),
            Some((1, 99))
        );
        assert_eq!(version_number("cargo 1.91.0-nightly"), Some((1, 91)));
        for bad in [
            "cargoc 1.99.0",
            "rustup 1.99.0",
            "other 2.0",
            "cargo unknown",
        ] {
            assert_eq!(version_number(bad), None);
        }
    }
}
