//! Optional user-level Cargo integration. The real rustup Cargo binary is never replaced.
use crate::{
    cargo,
    config::{Config, home},
    fail,
    util::{absolute, atomic_write, check_path},
};
use serde::{Deserialize, Serialize};
use std::{
    env, fs,
    path::{Path, PathBuf},
};

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct IntegrationState {
    pub shim_dir: PathBuf,
    pub real_cargo: PathBuf,
    pub enabled: bool,
    #[serde(default)]
    pub config_path: Option<PathBuf>,
}

pub fn state_path() -> PathBuf {
    home().join(".cargoc").join("integration.toml")
}
pub fn shim_dir() -> PathBuf {
    home().join(".cargoc").join("bin")
}

pub fn find_real_cargo(exclude: Option<&Path>) -> crate::Result<PathBuf> {
    cargo::resolve(Path::new("cargo"), exclude)
}

fn load_state() -> crate::Result<Option<IntegrationState>> {
    let path = state_path();
    if !path.exists() {
        return Ok(None);
    }
    Ok(Some(toml::from_str(&fs::read_to_string(path)?)?))
}

fn save_state(state: &IntegrationState) -> crate::Result<()> {
    atomic_write(&state_path(), toml::to_string_pretty(state)?.as_bytes())
}

#[cfg(windows)]
fn shim_path() -> PathBuf {
    shim_dir().join("cargo.exe")
}
#[cfg(not(windows))]
fn shim_path() -> PathBuf {
    shim_dir().join("cargo")
}

fn shell_script(executable: &str, config: &str) -> String {
    fn quote(value: &str) -> String {
        format!("'{}'", value.replace('\'', "'\"'\"'"))
    }
    let executable = if cfg!(windows) {
        executable.replace('\\', "/")
    } else {
        executable.to_owned()
    };
    let config = if cfg!(windows) {
        config.replace('\\', "/")
    } else {
        config.to_owned()
    };
    format!(
        "#!/bin/sh\n# Generated by cargoc.\nexec {} --cargoc-config {} exec \"$@\"\n",
        quote(&executable),
        quote(&config)
    )
}

fn shim_paths() -> Vec<PathBuf> {
    std::iter::once(shim_path())
        .chain(cfg!(windows).then(|| shim_dir().join("cargo.cmd")))
        .chain(cfg!(windows).then(|| shim_dir().join("cargo")))
        .collect()
}

fn check_shims() -> crate::Result<()> {
    for path in shim_paths() {
        check_path(&path)?;
        let owned = if !path.exists() {
            true
        } else if cfg!(windows) && path == shim_path() {
            crate::native_shim::inspect(&path)?.is_some()
        } else {
            cargo::generated_shim(&path)?
        };
        if !owned {
            return fail(format!(
                "Refusing to replace or delete an unowned shim: {}",
                path.display()
            ));
        }
    }
    Ok(())
}

fn write_shim(executable: &Path, config_path: &Path) -> crate::Result<()> {
    #[cfg(windows)]
    crate::native_shim::install(&shim_path(), executable, config_path)?;
    let executable = executable
        .to_str()
        .ok_or("cargoc path is not valid UTF-8")?;
    check_path(&shim_dir())?;
    fs::create_dir_all(shim_dir())?;
    let config_path = absolute(config_path)?;
    let config = config_path
        .to_str()
        .ok_or("Config path is not valid UTF-8")?;
    #[cfg(windows)]
    {
        let content = format!(
            "@echo off\r\nrem Generated by cargoc.\r\nsetlocal DisableDelayedExpansion\r\n\"{}\" --cargoc-config \"{}\" exec %*\r\nexit /b %errorlevel%\r\n",
            executable.replace('%', "%%"),
            config.replace('%', "%%")
        );
        atomic_write(&shim_dir().join("cargo.cmd"), content.as_bytes())?;
        // Git Bash does not resolve cargo.cmd when the command is named cargo.
        atomic_write(
            &shim_dir().join("cargo"),
            shell_script(executable, config).as_bytes(),
        )?;
    }
    #[cfg(not(windows))]
    atomic_write(&shim_path(), shell_script(executable, config).as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut permissions = fs::metadata(shim_path())?.permissions();
        permissions.set_mode(0o755);
        fs::set_permissions(shim_path(), permissions)?;
    }
    Ok(())
}

#[cfg(windows)]
fn user_path() -> crate::Result<Option<(String, String)>> {
    crate::windows_path::read()
}

#[cfg(windows)]
fn set_user_path(value: &str, kind: &str) -> crate::Result<()> {
    crate::windows_path::write(value, kind)
}

#[cfg(any(windows, test))]
fn path_entry_matches(entry: &str, shim: &str) -> bool {
    let mut expanded = String::new();
    let mut rest = entry.trim().trim_matches('"');
    while let Some(start) = rest.find('%') {
        expanded.push_str(&rest[..start]);
        let tail = &rest[start + 1..];
        let Some(end) = tail.find('%') else {
            expanded.push_str(&rest[start..]);
            rest = "";
            break;
        };
        let variable = &tail[..end];
        expanded.push_str(&env::var(variable).unwrap_or_else(|_| format!("%{variable}%")));
        rest = &tail[end + 1..];
    }
    expanded.push_str(rest);
    expanded
        .replace('/', "\\")
        .trim_end_matches('\\')
        .eq_ignore_ascii_case(shim.replace('/', "\\").trim_end_matches('\\'))
}

#[cfg(any(windows, test))]
fn without_shim(value: &str, shim: &str) -> String {
    value
        .split(';')
        .filter(|entry| !path_entry_matches(entry, shim))
        .collect::<Vec<_>>()
        .join(";")
}

#[cfg(any(windows, test))]
fn prepend_shim(value: &str, shim: &str) -> String {
    let matches = value
        .split(';')
        .filter(|entry| path_entry_matches(entry, shim))
        .count();
    if matches == 1
        && value
            .split(';')
            .next()
            .is_some_and(|entry| path_entry_matches(entry, shim))
    {
        return value.to_owned();
    }
    let remaining = without_shim(value, shim);
    if remaining.is_empty() {
        shim.to_owned()
    } else {
        format!("{shim};{remaining}")
    }
}

#[cfg(windows)]
fn enable_path() -> crate::Result<()> {
    let (kind, value) = user_path()?.unwrap_or(("REG_EXPAND_SZ".into(), String::new()));
    let shim = shim_dir().to_string_lossy().to_string();
    let new_value = prepend_shim(&value, &shim);
    if new_value == value {
        return Ok(());
    }
    set_user_path(&new_value, &kind)
}

#[cfg(windows)]
fn disable_path() -> crate::Result<()> {
    let Some((kind, value)) = user_path()? else {
        return Ok(());
    };
    let shim = shim_dir().to_string_lossy().to_string();
    let new_value = without_shim(&value, &shim);
    set_user_path(&new_value, &kind)
}

#[cfg(not(windows))]
fn enable_path() -> crate::Result<()> {
    // Do not silently edit shell startup files. The printed command is safe to
    // inspect and works for the current shell without guessing the user's shell.
    Ok(())
}
#[cfg(not(windows))]
fn disable_path() -> crate::Result<()> {
    Ok(())
}

pub fn enable(
    config: Config,
    config_path: &Path,
    explicit_cargo: Option<PathBuf>,
) -> crate::Result<()> {
    enable_with_path(config, config_path, explicit_cargo, enable_path)
}

fn enable_with_path(
    mut config: Config,
    config_path: &Path,
    explicit_cargo: Option<PathBuf>,
    update_path: impl FnOnce() -> crate::Result<()>,
) -> crate::Result<()> {
    let real = if let Some(path) = explicit_cargo {
        cargo::resolve(&path, None)?
    } else if config.cargo != Path::new("cargo") {
        cargo::resolve(&config.cargo, None)?
    } else {
        find_real_cargo(Some(&shim_dir()))?
    };
    // Preflight everything before config, shim, registry or state writes.
    cargo::verify(&real)?;
    check_shims()?;
    check_path(&state_path())?;
    config.cargo = real.clone();
    config.validate()?;
    if crate::util::same_or_descendant(config_path, &config.cache_dir)? {
        return fail("Config must be outside cache_dir");
    }
    crate::store::Store::open(config.clone(), true)?;
    config.save(config_path)?;
    write_shim(&absolute(&std::env::current_exe()?)?, config_path)?;
    update_path()?;
    save_state(&IntegrationState {
        shim_dir: shim_dir(),
        real_cargo: real,
        enabled: true,
        config_path: Some(absolute(config_path)?),
    })?;
    println!("cargoc default Cargo integration installed.");
    println!("Shim: {}", shim_path().display());
    println!("Real Cargo: {}", config.cargo.display());
    #[cfg(windows)]
    println!("Reopen your terminal for the user PATH change to take effect.");
    #[cfg(not(windows))]
    println!("Add this directory before the Rustup bin directory in your shell PATH:");
    #[cfg(not(windows))]
    println!("  export PATH=\"{}:$PATH\"", shim_dir().display());
    Ok(())
}

pub fn disable() -> crate::Result<()> {
    disable_with_path(disable_path)
}

fn disable_with_path(update_path: impl FnOnce() -> crate::Result<()>) -> crate::Result<()> {
    if let Some(state) = load_state()? {
        check_shims()?;
        update_path()?;
        for path in shim_paths() {
            if path.exists() {
                check_path(&path)?;
                fs::remove_file(path)?;
            }
        }
        save_state(&IntegrationState {
            enabled: false,
            ..state
        })?;
        println!(
            "cargoc default Cargo integration disabled; the original Cargo path is unchanged."
        );
        #[cfg(windows)]
        println!("Reopen your terminal for the user PATH restoration to take effect.");
    } else {
        println!("No cargoc default Cargo integration is registered.");
    }
    Ok(())
}

pub fn status() -> crate::Result<()> {
    match load_state()? {
        Some(state) if state.enabled => {
            let installed = shim_paths().iter().all(|path| path.is_file()) && check_shims().is_ok();
            let search = env::var_os("PATH").unwrap_or_default();
            let selected = cargo::candidates(Path::new("cargo"), &search)
                .into_iter()
                .find(|path| {
                    if !path.is_file() {
                        return false;
                    }
                    #[cfg(unix)]
                    {
                        use std::os::unix::fs::PermissionsExt;
                        if path
                            .metadata()
                            .is_ok_and(|m| m.permissions().mode() & 0o111 == 0)
                        {
                            return false;
                        }
                    }
                    true
                });
            let active = installed
                && selected.as_ref().is_some_and(|path| {
                    shim_paths().iter().any(|shim| {
                        matches!((crate::util::identity_path(path), crate::util::identity_path(shim)), (Ok(a), Ok(b)) if a == b)
                    })
                });
            let config = state.config_path.as_ref().map(|path| Config::load(path));
            let config_valid = config.as_ref().is_none_or(|result| result.is_ok());
            let configured = config
                .and_then(Result::ok)
                .map_or(state.real_cargo, |config| config.cargo);
            let resolved = cargo::resolve(&configured, None);
            let real_valid = resolved
                .as_ref()
                .is_ok_and(|path| cargo::verify(path).is_ok());
            let real = resolved.unwrap_or(configured);
            println!(
                "registered: shim={} real_cargo={}",
                shim_path().display(),
                real.display()
            );
            println!(
                "shim_installed={installed} active_in_current_path={active} real_cargo_valid={real_valid} config_valid={config_valid}"
            );
            if let Some(path) = selected {
                println!("current_path_cargo={}", path.display());
            }
            if !active {
                println!(
                    "The shim is not selected in this process; reopen the terminal or put the shim directory first on PATH."
                );
            }
            println!(
                "PATH checks do not detect shell aliases/functions or absolute-path invocations."
            );
        }
        _ => println!("disabled"),
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn path_enable_moves_late_shims_to_front_without_changing_other_entries() {
        let shim = r"C:\Users\User\.cargoc\bin";
        let original = r"C:\Tools;;%UNRELATED_VAR%\工具;C:\Rust\bin;";
        let enabled = prepend_shim(original, shim);
        assert_eq!(enabled, format!("{shim};{original}"));
        assert_eq!(prepend_shim(&enabled, shim), enabled);
        assert_eq!(without_shim(&enabled, shim), original);
        let late = format!(
            "C:\\Tools;{};C:\\Rust\\bin;{}",
            shim.to_lowercase().replace('\\', "/") + "/",
            shim
        );
        assert_eq!(
            prepend_shim(&late, shim),
            format!("{shim};C:\\Tools;C:\\Rust\\bin")
        );
        assert!(path_entry_matches(&format!("\"{shim}\\\""), shim));
        assert!(!path_entry_matches(&(shim.to_owned() + "-other"), shim));
    }

    // Child-process environment isolation; the injected callback is the only PATH
    // operation, so this exercises setup/refresh/disable without registry writes.
    #[cfg(windows)]
    #[test]
    fn native_setup_lifecycle_without_registry() {
        use std::process::Command;
        const CHILD: &str = "CARGOC_NATIVE_LIFECYCLE_CHILD";
        if env::var_os(CHILD).is_none() {
            let dir = tempfile::tempdir().unwrap();
            let fake = dir.path().join("real-cargo.exe");
            let compiled = Command::new(env::var_os("RUSTC").unwrap_or_else(|| "rustc".into()))
                .args(["--edition=2021", "-o"])
                .arg(&fake)
                .arg(Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/fake_cargo.rs"))
                .output()
                .unwrap();
            assert!(
                compiled.status.success(),
                "{}",
                String::from_utf8_lossy(&compiled.stderr)
            );
            // Both native-first and legacy-script-first PATHEXT orders select
            // an owned shim; status must not report a false bypass.
            for extensions in [".EXE;.CMD;.COM;.BAT", ".CMD;.EXE;.BAT;.COM"] {
                let output = Command::new(env::current_exe().unwrap())
                    .args([
                        "--exact",
                        "integration::tests::native_setup_lifecycle_without_registry",
                        "--nocapture",
                    ])
                    .env(CHILD, &fake)
                    .env("HOME", dir.path())
                    .env("USERPROFILE", dir.path())
                    .env("CARGO_HOME", dir.path().join("cargo-home"))
                    .env("PATH", dir.path().join(".cargoc/bin"))
                    .env("PATHEXT", extensions)
                    .output()
                    .unwrap();
                assert!(
                    output.status.success(),
                    "stdout={} stderr={}",
                    String::from_utf8_lossy(&output.stdout),
                    String::from_utf8_lossy(&output.stderr)
                );
                let text = String::from_utf8_lossy(&output.stdout);
                assert!(
                    text.contains("shim_installed=true active_in_current_path=true"),
                    "{text}"
                );
                assert!(text.contains("shim_installed=false"), "{text}");
            }
            return;
        }
        let fake = PathBuf::from(env::var_os(CHILD).unwrap());
        let config_path = home().join("fixed config.toml");
        let config = Config {
            cargo: fake,
            cache_dir: home().join("cache"),
            min_free_gib: 0.0,
            abort_free_gib: 0.0,
            ..Config::default()
        };
        fs::create_dir_all(shim_dir()).unwrap();
        // Upgrade from the previous two owned scripts.
        fs::write(shim_dir().join("cargo.cmd"), "rem Generated by cargoc.\r\n").unwrap();
        fs::write(shim_dir().join("cargo"), "# Generated by cargoc.\n").unwrap();
        enable_with_path(config.clone(), &config_path, None, || Ok(())).unwrap();
        assert!(shim_paths().iter().all(|p| p.is_file()));
        status().unwrap();
        // Old registered two-script installations are inactive until upgraded.
        fs::remove_file(shim_path()).unwrap();
        status().unwrap();
        let refreshed = home().join("refreshed config.toml");
        enable_with_path(config.clone(), &refreshed, None, || Ok(())).unwrap();
        assert_eq!(
            crate::native_shim::inspect(&shim_path())
                .unwrap()
                .unwrap()
                .config,
            refreshed
        );
        // A corrupted native image cannot be refreshed or deleted.
        let original = fs::read(shim_path()).unwrap();
        let mut corrupt = original.clone();
        corrupt[2] ^= 1;
        fs::write(shim_path(), &corrupt).unwrap();
        let before = fs::read(&refreshed).unwrap();
        assert!(
            enable_with_path(config.clone(), &refreshed, None, || panic!("PATH changed")).is_err()
        );
        assert!(disable_with_path(|| panic!("PATH changed")).is_err());
        assert_eq!(fs::read(&refreshed).unwrap(), before);
        assert_eq!(fs::read(shim_path()).unwrap(), corrupt);
        status().unwrap();
        fs::write(shim_path(), "user executable").unwrap();
        assert!(disable_with_path(|| panic!("PATH changed")).is_err());
        assert!(enable_with_path(config, &refreshed, None, || panic!("PATH changed")).is_err());
        assert_eq!(fs::read(shim_path()).unwrap(), b"user executable");
        fs::write(shim_path(), original).unwrap();
        disable_with_path(|| Ok(())).unwrap();
        assert!(shim_paths().iter().all(|p| !p.exists()));
        assert!(!load_state().unwrap().unwrap().enabled);
    }

    #[test]
    fn shell_shim_quotes_paths_and_forwards_all_arguments() {
        let script = shell_script("/tmp/a'b tool", "/tmp/$(not-a-command)/config.toml");
        assert!(script.contains("'/tmp/a'\"'\"'b tool'"));
        assert!(script.contains("'/tmp/$(not-a-command)/config.toml'"));
        assert!(script.ends_with("exec \"$@\"\n"));
    }
}
