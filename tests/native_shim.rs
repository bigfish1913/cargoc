use cargoc::native_shim;
use std::{fs, path::Path};
#[cfg(windows)]
use std::{
    path::PathBuf,
    process::{Command, Output},
    sync::OnceLock,
};
use tempfile::TempDir;

fn temp() -> TempDir {
    tempfile::tempdir_in(fs::canonicalize(std::env::temp_dir()).unwrap()).unwrap()
}

#[test]
fn trailer_ownership_is_not_a_filename_or_script_marker() {
    let dir = temp();
    let target = dir.path().join("cargoc.exe");
    fs::copy(env!("CARGO_BIN_EXE_cargoc"), &target).unwrap();
    let proxy = dir.path().join("cargo.exe");
    fs::write(&proxy, b"MZ arbitrary exe rem Generated by cargoc.").unwrap();
    assert!(native_shim::inspect(&proxy).unwrap().is_none());
    assert!(native_shim::install(&proxy, &target, &dir.path().join("config")).is_err());
    assert_eq!(
        fs::read(&proxy).unwrap(),
        b"MZ arbitrary exe rem Generated by cargoc."
    );
    fs::remove_file(&proxy).unwrap();
    native_shim::install(&proxy, &target, &dir.path().join("config")).unwrap();
    let original = fs::read(&proxy).unwrap();
    assert_eq!(
        native_shim::inspect(&proxy).unwrap().unwrap().target,
        target
    );
    let renamed = dir.path().join("renamed.exe");
    fs::copy(&proxy, &renamed).unwrap();
    assert!(native_shim::inspect(&renamed).unwrap().is_some());
    assert!(cargoc::cargo::validate_path(&renamed).is_err());
    // Changing either executable bytes or the metadata/padding invalidates ownership.
    for index in [2, original.len() - 100, original.len() - 1] {
        let mut tampered = original.clone();
        tampered[index] ^= 1;
        fs::write(&proxy, &tampered).unwrap();
        assert!(native_shim::inspect(&proxy).is_err());
        assert!(native_shim::install(&proxy, &target, &dir.path().join("config")).is_err());
        assert_eq!(fs::read(&proxy).unwrap(), tampered);
    }
    for removed in [1, 32, 10_000, 32_760] {
        fs::write(&proxy, &original[..original.len() - removed]).unwrap();
        assert!(native_shim::inspect(&proxy).is_err(), "removed={removed}");
    }
    fs::write(&proxy, &original).unwrap();
    let config2 = dir.path().join("new config 工具.toml");
    native_shim::install(&proxy, &target, &config2).unwrap();
    assert_eq!(
        native_shim::inspect(&proxy).unwrap().unwrap().config,
        config2
    );
}

#[test]
fn install_rejects_missing_self_and_nested_targets() {
    let dir = temp();
    let proxy = dir.path().join("cargo.exe");
    let target = Path::new(env!("CARGO_BIN_EXE_cargoc"));
    let config = dir.path().join("config");
    assert!(native_shim::install(&proxy, &dir.path().join("missing.exe"), &config).is_err());
    native_shim::install(&proxy, target, &config).unwrap();
    let before = fs::read(&proxy).unwrap();
    assert!(native_shim::install(&proxy, &proxy, &config).is_err());
    assert!(native_shim::install(&dir.path().join("nested.exe"), &proxy, &config).is_err());
    assert_eq!(fs::read(proxy).unwrap(), before);
}

#[cfg(windows)]
fn fake_cargo() -> &'static PathBuf {
    static COMPILED: OnceLock<(TempDir, PathBuf)> = OnceLock::new();
    &COMPILED
        .get_or_init(|| {
            let dir = temp();
            let out = dir.path().join("fake-cargo.exe");
            let output = Command::new(std::env::var_os("RUSTC").unwrap_or_else(|| "rustc".into()))
                .arg("--edition=2021")
                .arg(Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/fake_cargo.rs"))
                .arg("-o")
                .arg(&out)
                .output()
                .unwrap();
            success(&output);
            (dir, out)
        })
        .1
}

#[cfg(windows)]
fn success(output: &Output) {
    assert!(
        output.status.success(),
        "stdout={} stderr={}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

#[cfg(windows)]
struct Fixture {
    dir: TempDir,
    proxy: PathBuf,
    config: PathBuf,
    target: PathBuf,
}
#[cfg(windows)]
impl Fixture {
    fn new() -> Self {
        let dir = temp();
        let config = dir.path().join("fixed config 工具.toml");
        let workspace = dir.path().join("workspace with spaces");
        fs::create_dir_all(&workspace).unwrap();
        fs::write(workspace.join("Cargo.toml"), "source").unwrap();
        cargoc::config::Config {
            cargo: fake_cargo().clone(),
            cache_dir: dir.path().join("cache"),
            min_free_gib: 0.0,
            abort_free_gib: 0.0,
            max_age_days: 0.0,
            poll_seconds: 0.1,
            ..Default::default()
        }
        .save(&config)
        .unwrap();
        let target = dir.path().join("actual cargoc 工具.exe");
        fs::copy(env!("CARGO_BIN_EXE_cargoc"), &target).unwrap();
        let proxy = dir.path().join("cargo.exe");
        native_shim::install(&proxy, &target, &config).unwrap();
        Self {
            dir,
            proxy,
            config,
            target,
        }
    }
    fn command(&self) -> Command {
        let root = self.dir.path();
        let workspace = root.join("workspace with spaces");
        let mut cmd = Command::new(&self.proxy);
        cmd.current_dir(&workspace)
            .env("HOME", root)
            .env("USERPROFILE", root)
            .env("CARGO_HOME", root.join("cargo-home"))
            .env("CARGOC_CONFIG", root.join("must-not-use.toml"))
            .env("CARGOC_FORWARD_DEPTH", "0")
            .env("FAKE_WORKSPACE", &workspace)
            .env("FAKE_MANIFEST", workspace.join("Cargo.toml"))
            .env("FAKE_ARGUMENTS", root.join("args.json"));
        cmd
    }
}

#[cfg(windows)]
#[test]
fn direct_native_command_preserves_raw_arguments_and_fixed_configuration() {
    let f = Fixture::new();
    let args = [
        "run",
        "--release",
        "--",
        "space value",
        "工具 café",
        "a\"b",
        "trailing\\",
        "--cargoc-config",
        "not-the-wrapper-config",
        "--config",
        "application value",
    ];
    success(&f.command().args(args).output().unwrap());
    let recorded: Vec<String> =
        serde_json::from_slice(&fs::read(f.dir.path().join("args.json")).unwrap()).unwrap();
    assert_eq!(&recorded[2..], args);
    // Leading global-looking options must also be Cargo's, not Clap's.
    success(
        &f.command()
            .args(["--cargoc-config", "not-the-wrapper-config", "check"])
            .output()
            .unwrap(),
    );
    let recorded: Vec<String> =
        serde_json::from_slice(&fs::read(f.dir.path().join("args.json")).unwrap()).unwrap();
    assert_eq!(
        &recorded[2..],
        ["--cargoc-config", "not-the-wrapper-config", "check"]
    );
    assert!(f.config.exists());
    let failed = f
        .command()
        .arg("test")
        .env("FAKE_MODE", "fail")
        .output()
        .unwrap();
    assert_eq!(failed.status.code(), Some(7));
}

#[cfg(windows)]
#[test]
fn native_version_banner_and_error_stream_are_preserved() {
    let mut f = Fixture::new();
    for args in [
        vec!["--version"],
        vec!["-vV"],
        vec!["+stable", "--version", "--verbose"],
    ] {
        let output = f.command().args(args).output().unwrap();
        success(&output);
        let text = String::from_utf8(output.stdout).unwrap();
        assert!(text.starts_with("cargo 1.99.0 (test)\n"), "{text}");
        assert!(
            text.ends_with(&format!("cargoc {}\n", env!("CARGO_PKG_VERSION"))),
            "{text}"
        );
    }
    let renamed = f.dir.path().join("not-called-cargo.exe");
    fs::copy(&f.proxy, &renamed).unwrap();
    f.proxy = renamed;
    success(&f.command().arg("--version").output().unwrap());
    let output = f
        .command()
        .arg("--version")
        .env("FAKE_MODE", "version-fail")
        .output()
        .unwrap();
    assert_eq!(output.status.code(), Some(7));
    assert!(output.stdout.is_empty());
    assert!(String::from_utf8_lossy(&output.stderr).contains("native version failure"));
}

#[cfg(windows)]
#[test]
fn runtime_rejects_missing_nested_self_corrupt_and_excessive_depth() {
    let f = Fixture::new();
    let output = f
        .command()
        .arg("--version")
        .env("CARGOC_FORWARD_DEPTH", "8")
        .output()
        .unwrap();
    assert_eq!(output.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&output.stderr).contains("recursion"));
    let target_image = fs::read(&f.target).unwrap();
    let proxy_image = fs::read(&f.proxy).unwrap();
    fs::remove_file(&f.target).unwrap();
    let output = f.command().arg("--version").output().unwrap();
    assert_eq!(output.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&output.stderr).contains("missing"));
    fs::write(&f.target, &proxy_image).unwrap();
    let output = f.command().arg("--version").output().unwrap();
    assert_eq!(output.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&output.stderr).contains("recursion"));
    // Run the proxy at its own recorded target path.
    let output = Command::new(&f.target)
        .arg("--version")
        .env("HOME", f.dir.path())
        .env("USERPROFILE", f.dir.path())
        .env("CARGO_HOME", f.dir.path().join("cargo-home"))
        .output()
        .unwrap();
    assert_eq!(output.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&output.stderr).contains("itself"));
    fs::write(&f.target, target_image).unwrap();
    fs::write(&f.proxy, &proxy_image[..proxy_image.len() - 10]).unwrap();
    let output = f.command().arg("--version").output().unwrap();
    assert_eq!(output.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&output.stderr).contains("Corrupt"));
}

#[cfg(windows)]
#[test]
fn discovery_skips_native_copies_outside_the_standard_shim_directory() {
    let f = Fixture::new();
    let first = f.dir.path().join("foreign proxy directory");
    let second = f.dir.path().join("real cargo directory");
    fs::create_dir_all(&first).unwrap();
    fs::create_dir_all(&second).unwrap();
    fs::copy(&f.proxy, first.join("cargo.exe")).unwrap();
    let real = second.join("cargo.exe");
    fs::copy(fake_cargo(), &real).unwrap();
    let mut config = cargoc::config::Config::load(&f.config).unwrap();
    config.cargo = "cargo".into();
    config.save(&f.config).unwrap();
    let recorded = f.dir.path().join("selected.txt");
    let output = f
        .command()
        .arg("--version")
        .env("PATH", std::env::join_paths([first, second]).unwrap())
        .env("PATHEXT", ".EXE;.CMD")
        .env("FAKE_VERSION_EXECUTABLE", &recorded)
        .output()
        .unwrap();
    success(&output);
    let selected = fs::read_to_string(recorded).unwrap();
    assert_eq!(
        cargoc::util::identity_path(Path::new(&selected)).unwrap(),
        cargoc::util::identity_path(&real).unwrap()
    );
}

#[cfg(windows)]
#[test]
fn native_proxy_installs_use_managed_records_and_clean_preserves_final_outputs() {
    for args in [
        vec!["install", "demo", "--registry", "local"],
        vec![
            "install",
            "--git",
            "https://example.invalid/demo",
            "--rev",
            "abc",
        ],
        vec!["install", "--path", "."],
    ] {
        let f = Fixture::new();
        success(&f.command().args(args).output().unwrap());
        let config = cargoc::config::Config::load(&f.config).unwrap();
        let store = cargoc::store::Store::open(config, false).unwrap();
        let entries = store.entries().unwrap();
        assert_eq!(entries.len(), 1);
        assert_eq!(entries[0].record.kind, cargoc::store::CacheKind::Install);
        assert!(entries[0].bytes > 0);
        success(
            &Command::new(&f.target)
                .arg("--cargoc-config")
                .arg(&f.config)
                .arg("clean")
                .output()
                .unwrap(),
        );
        assert_eq!(store.entries().unwrap()[0].bytes, 0);
        assert!(
            f.dir
                .path()
                .join("workspace with spaces/target/debug/demo.exe")
                .is_file()
        );
    }
}
